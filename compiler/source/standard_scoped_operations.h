/* Argument positions: the view follows the optional extra argument; the deadline is last. */
static inline uint32_t
r_standard_scoped_view_index(const RStandardScopedOperationDescriptor *descriptor) {
    return descriptor->extra_type == NULL ? UINT32_C(1) : UINT32_C(2);
}

static inline uint32_t
r_standard_scoped_argument_count(const RStandardScopedOperationDescriptor *descriptor) {
    return r_standard_scoped_view_index(descriptor) + UINT32_C(2);
}

