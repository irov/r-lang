/* A scoped standard operation (Library R-SLIB-ASYNC-0012) borrows a caller view for the
   lifetime of a task-group loan (Core R-STMT-0017). Arguments are the shared handle borrow,
   an optional by-value extra argument, the byte view and the deadline, in that order. The extra
   argument is a named standard type or u64. */
typedef struct RStandardScopedOperationDescriptor {
    RStandardCallOperation operation;
    const char *module;      /* "std.io", "std.fs" or "std.net" */
    const char *name;        /* unqualified operation name */
    const char *handle_type; /* named standard type behind the shared borrow */
    const char *extra_type;  /* by-value argument before the view, or NULL */
    bool exclusive_view;     /* u8[] when true, const u8[] otherwise */
    const char *result_type; /* "usize", "void" or a named standard type */
    const char *error_type;  /* the single checked completion error */
    const char *rule;
    const char *native_name; /* C start function */
    const char *c_deadline;  /* C deadline struct */
    const char *c_start;     /* C start result struct */
    const char *c_view;      /* C view struct with data/length members */
} RStandardScopedOperationDescriptor;

