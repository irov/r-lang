module example.unzip.tests.dynamic_huffman;

import example.unzip.deflate::{decode};
import example.unzip.error::{ZipError};

bool dynamic_huffman_decodes_and_matches_crc() {
    // Raw dynamic-Huffman DEFLATE for 80 repeated English sentences plus "END".
    u8[75] compressed = {
        0xed, 0xca, 0xd9, 0x11, 0x40, 0x40, 0x14, 0x05,
        0xd1, 0x54, 0x6e, 0x04, 0xa2, 0xe0, 0x57, 0x0e,
        0x96, 0xb1, 0xf3, 0x18, 0x63, 0x8d, 0x9e, 0x12,
        0x86, 0xea, 0xcf, 0xae, 0x3e, 0xa1, 0x71, 0x5a,
        0xb6, 0xb6, 0xe8, 0x95, 0x7b, 0x3b, 0x26, 0x55,
        0x76, 0xaa, 0xdb, 0xc6, 0x79, 0x95, 0xed, 0xce,
        0x2b, 0xbc, 0x7b, 0xc8, 0xee, 0x4b, 0xa5, 0xd5,
        0xd1, 0x57, 0x60, 0x30, 0x18, 0x0c, 0x06, 0x83,
        0xc1, 0x60, 0x30, 0x18, 0x0c, 0xfe, 0x05, 0x4e,
        0xd2, 0xf8, 0x01,
    };
    u8[3_603] output = {};
    const u8[] input = &compressed;
    u8[] destination = &output;
    try {
        usize size = decode(input, destination, 3_603);
        if (size != 3_603) {
            return false;
        }
        const u8[] output_view = &output;
        u32 crc = std.hash::crc32(output_view);
        if (crc != 0x5810_489d) {
            return false;
        }
        return true;
    } catch (ZipError error) {
        error as void;
        return false;
    }
}
